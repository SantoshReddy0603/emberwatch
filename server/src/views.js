export function sensorView(st) {
  const {
    id,
    idx,
    type,
    zone,
    lat,
    lng,
    site,
    seq,
    ts,
    lastSeen,
    t,
    h,
    s,
    co,
    ws,
    wd,
    b,
    rssi,
    fdi,
    status,
    z,
  } = st;
  return {
    id,
    idx,
    type,
    zone,
    lat,
    lng,
    site,
    seq,
    ts,
    lastSeen,
    t,
    h,
    s,
    co,
    ws,
    wd,
    b,
    rssi,
    fdi,
    status,
    z,
  };
}

export const snapshot = (core, zones) => ({
  epoch: core.epoch,
  ts: Date.now(),
  devices: core.state.list.filter((st) => zones.includes(st.zone)).map(sensorView),
});
